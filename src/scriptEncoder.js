// Microsoft Script Encoder (screnc.exe): JScript.Encode / VBScript.Encode, `.jse` / `.vbe` files.
//
// Not encryption: a fixed substitution with three alphabets, chosen per character by a repeating
// 64-entry pattern. A block looks like
//
//   #@~^LLLLLL==<encoded text>CCCCCC==^#~@
//
// with LLLLLL the encoded length and CCCCCC the sum of the decoded character codes, both as six
// base64 digits in a scrambled order. Inside the text `@#` `@&` `@!` `@*` `@$` stand for
// \r \n < > @ and take one position of the pattern; characters >= 0x80 are copied as is and take
// none. The tables below agree with Wine's dlls/jscript/decode.c and with scrdec 1.8.

