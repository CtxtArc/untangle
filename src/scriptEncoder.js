const ESCAPES = { '#': '\r', '&': '\n', '!': '<', '*': '>', $: '@' };
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

/** The length / checksum field: six base64 digits in screnc's byte order, then "==". */
export function decodeNumber(s) {
  if (s.length < 8 || s[6] !== '=' || s[7] !== '=') return null;
  const d = [...s.slice(0, 6)].map((c) => B64.indexOf(c));
  if (d.some((x) => x < 0)) return null;
  return ((d[0] << 2) + (d[1] >> 4) + ((d[1] & 0xf) << 12) + ((d[2] >> 2) << 8) + ((d[2] & 3) << 22) +
    (d[3] << 16) + ((d[4] << 2) << 24) + ((d[5] >> 4) << 24)) >>> 0;
}

export function encodeNumber(n) {
  // inverse of decodeNumber, for tests and round trips
  const d = [
    (n >> 2) & 63, ((n & 3) << 4) | ((n >> 12) & 15), ((n >> 6) & 0x3c) | ((n >> 22) & 3),
    (n >> 16) & 63, (n >> 26) & 63, ((n >> 24) & 3) << 4,
  ];
  return d.map((x) => B64[x]).join('') + '==';
}

function decodeText(data) {
  let out = '';
  let pos = 0;
  let sum = 0;
  for (let i = 0; i < data.length; i++) {
    const c = data.charCodeAt(i);
    let ch;
    if (data[i] === '@' && i + 1 < data.length) {
      ch = ESCAPES[data[++i]];
      if (ch === undefined) ch = '?';
      pos++;
    } else if (c < 0x80) {
      ch = String.fromCharCode(DECODE[c][PICK[pos % 64]]);
      pos++;
    } else {
      ch = data[i]; // already decoded by the input codepage; screnc leaves these alone
    }
    out += ch;
    sum = (sum + ch.charCodeAt(0)) >>> 0;
  }
  return { out, sum };
}

/**
 * Replace every `#@~^…^#~@` block by its plaintext.
 * @returns {{ code: string, blocks: number, badChecksums: number }}
 */
export function decodeScriptEncoder(text) {
  let code = '';
  let blocks = 0;
  let badChecksums = 0;
  let at = 0;
  for (;;) {
    const start = text.indexOf('#@~^', at);
    if (start < 0) break;
    const end = text.indexOf('^#~@', start + 4);
    const len = decodeNumber(text.slice(start + 4, start + 12));
    if (end < 0 || len === null || end - 8 < start + 12) break; // not a block: leave the rest alone
    const data = text.slice(start + 12, end - 8);
    const csum = decodeNumber(text.slice(end - 8, end));
    const { out, sum } = decodeText(data);
    if (csum === null || csum !== sum || len !== data.length) badChecksums++;
    let before = text.slice(at, start);
    // screnc keeps the `//**Start Encode**` marker comment on the same line as the block
    const line = before.slice(before.lastIndexOf('\n') + 1);
    if (/\/\//.test(line) && !/^\s*$/.test(line)) before += '\n';
    code += before + out;
    at = end + 4;
    blocks++;
  }
  return { code: code + text.slice(at), blocks, badChecksums };
}

/** screnc's encoder, the exact inverse of decodeText (tests build their samples with it). */
export function encodeScriptEncoder(plain) {
  const ENC = new Map();
  for (let c = 0; c < 0x80; c++) for (let k = 0; k < 3; k++) if (DECODE[c][k] && !ENC.has(`${k}:${DECODE[c][k]}`)) ENC.set(`${k}:${DECODE[c][k]}`, c);
  const REV = { '\r': '#', '\n': '&', '<': '!', '>': '*', '@': '$' };
  let data = '';
  let sum = 0;
  let pos = 0;
  for (const ch of plain) {
    sum = (sum + ch.charCodeAt(0)) >>> 0;
    if (REV[ch]) { data += '@' + REV[ch]; pos++; continue; }
    const c = ch.charCodeAt(0);
    if (c >= 0x80) { data += ch; continue; }
    const e = ENC.get(`${PICK[pos % 64]}:${c}`);
    if (e === undefined) throw new Error(`cannot encode U+${c.toString(16)}`);
    data += String.fromCharCode(e);
    pos++;
  }
  return `#@~^${encodeNumber(data.length)}${data}${encodeNumber(sum)}^#~@`;
}
